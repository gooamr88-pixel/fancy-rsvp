/**
 * True if `err` is a raised (not returned-as-jsonb) GUEST_LIMIT_REACHED
 * failure — currently only possible from submit_rsvp_v2's unique_violation
 * exception paths surfacing a P0001; most guest-cap checks (add_guest_to_party,
 * update_party_response) return `{ success: false, code/error: 'GUEST_LIMIT_REACHED' }`
 * as normal jsonb instead, handled via sendRpcFailure/result.success checks.
 */
const isGuestLimitError = (err) => err?.code === 'P0001' && /GUEST_LIMIT_REACHED/.test(err.message || '');

const EMAIL_RE = /^[^\s@]+@[^\s@]+\.[^\s@]+$/;

/**
 * Builds the reader for a CSV/XLSX "side" cell, for ONE event.
 *
 * Per-event rather than a module constant, and that is the bug fix rather than
 * an optimization. `exportParties` writes the RESOLVED label — sideLabelForEvent
 * turns 'partner1' into "Evan's Side" — while this matcher only ever knew the
 * generic synonyms ('groom', 'partner1', …). So the platform could not read its
 * OWN export back in: every side on every re-imported file silently became null,
 * with nothing reported to the organizer.
 *
 * The two event-specific spellings are generated by the same function the export
 * calls, so the round trip cannot drift — rename a partner and both ends move
 * together.
 */
const makeSideCsvNormalizer = (event) => {
  // Excel autocorrects a typed ' into U+2019, which an organizer editing an
  // exported file by hand hits on the first cell they touch.
  const key = (raw) => String(raw == null ? '' : raw).trim().toLowerCase().replace(/’/g, "'");

  const bySpelling = new Map();
  for (const side of ['partner1', 'partner2']) {
    const label = sideLabelForEvent(side, event);
    if (label) bySpelling.set(key(label), side);
  }

  // The neutral synonyms, plus the labels sideLabel itself falls back to when a
  // partner has no name on file — a file exported before the organizer filled
  // those in carries "Groom's Side" or "Partner 1's Side" verbatim.
  const SYNONYMS = {
    partner1: ['partner1', 'side1', 'groom', "groom's side", 'groom side', "partner 1's side"],
    partner2: ['partner2', 'side2', 'bride', "bride's side", 'bride side', "partner 2's side"],
  };
  for (const [side, spellings] of Object.entries(SYNONYMS)) {
    // A label the event actually uses wins. A partner genuinely named "Bride" is
    // rare but possible, and their own label must not lose to the generic one.
    for (const spelling of spellings) if (!bySpelling.has(spelling)) bySpelling.set(spelling, side);
  }

  return (raw) => bySpelling.get(key(raw)) || null;
};

/**
 * Reads a CSV/XLSX "response" cell into a storable value.
 *
 * Until now no such reader existed and the column was not mapped at all —
 * importGuests hardcoded 'pending' — so re-importing an export reset every
 * answer the organizer had already collected.
 *
 * Delegates the spellings to utils/responseHelpers, the same helpers the
 * dashboard and the exports read with, so a word accepted here is one the rest
 * of the app already agrees about. Anything unrecognised, blank, or from a file
 * with no such column is 'pending': the schema default, and the safe direction
 * to be wrong in, since a guest wrongly marked attending is counted in the
 * caterer's numbers and given a seat.
 */
/**
 * Placeholder words the .xlsx export writes where a CSV would leave the cell
 * empty — `N/A` for a missing email or phone, `Unassigned` for no table,
 * `None` for no meal.
 *
 * Without this, re-uploading an Excel export creates guests whose email is
 * literally "N/A" (and, since emails are unique per event, the SECOND such row
 * then collides and is skipped as a duplicate) and hunts for a table called
 * "Unassigned". The .xlsx guest sheet is a human report rather than an
 * interchange format — CSV is the round-trip contract — but an organizer cannot
 * be expected to know that from looking at two buttons side by side.
 */
const EXPORT_PLACEHOLDERS = new Set(['n/a', 'na', 'none', 'unassigned', '-', '—']);
const blankIfPlaceholder = (raw) => {
  const s = String(raw == null ? '' : raw).trim();
  return EXPORT_PLACEHOLDERS.has(s.toLowerCase()) ? '' : s;
};

const normalizeResponseCsvValue = (raw) => {
  const v = String(raw == null ? '' : raw).trim().toLowerCase();
  if (!v) return 'pending';
  if (isAcceptedResponse(v) || ['y', 'going', 'true', '1'].includes(v)) return 'yes';
  if (isDeclinedResponse(v) || ['n', 'regrets', 'false', '0'].includes(v)) return 'no';
  if (isMaybeResponse(v) || v === 'unsure') return 'maybe';
  return 'pending';
};

/**
 * Handles guest RSVP form submissions (insert or update).
 * All gating/validation/dedup/child-row writes happen atomically inside the
 * submit_rsvp_v2() RPC (see GuestService) — this handler only validates cheap
 * shape constraints up front, then fires the best-effort notification fanout
 * (confirmation/decline email, organizer notify, realtime broadcast).
 * POST /api/v1/public/events/:slug/rsvp
 */
const submitPublicRSVP = async (req, res, next) => {
  const { slug } = req.params;
  const { partyId, guestName, email, phone, response, partySize, notes, additionalGuests, primaryGuestMeal, primaryGuestDietaryNotes, customAnswers, decline_reason, maybe_confirm_by, side, smsConsent } = req.body;
  // The guest RSVP'd in a language they chose on the page — answer them in it.
  // Nothing is stored: this only styles the immediate confirmation/decline mail.
  const guestLang = String(req.body?.lang || '').toLowerCase().startsWith('ar') ? 'ar' : 'en';

  if (!guestName || !response) {
    return sendFail(res, { status: 400, error: 'VALIDATION_ERROR', message: 'guestName and response are required.' });
  }

  const isAttending = response === 'yes';

  /**
   * PHONE AND SMS CONSENT ARE REQUIRED — EXCEPT FROM A DECLINE.
   *
   * Both were optional between 2026-08-01 and 2026-09-04, deliberately, so that
   * a guest could complete an RSVP while staying entirely outside the messaging
   * program — which is what made "agreeing to receive messages" genuinely
   * optional under Twilio TFV 30475. That was reversed on the product owner's
   * explicit instruction; the full context, the risk and the required re-filing
   * are documented once, in
   * frontend/src/app/components/guest/SmsConsentText.js.
   *
   * ── THE DECLINE EXEMPTION ──
   *
   * A guest who says no receives no table, no entry pass, and no transactional
   * message of any kind — there is nothing this platform will ever text them.
   * Demanding consent from them would be a requirement with no purpose behind
   * it, and it would sit directly beneath a disclosure ("your table number,
   * your entry pass, and any change of date or venue are sent by text") that
   * does not describe anything they will receive.
   *
   * It matters to the compliance case, not only to the copy: the entire
   * argument for requiring consent is that every message is transactional about
   * an event the recipient chose to attend. A form demanding it from somebody
   * who has just said they are not attending contradicts that argument on the
   * screen a reviewer is looking at.
   *
   * 'maybe' is NOT exempt — they still receive date and venue changes, and they
   * can convert to a yes and be seated.
   *
   * ── WHY THIS IS ENFORCED HERE AND NOT ONLY IN THE FORM ──
   *
   * Two RSVP surfaces post to this endpoint (RsvpWizard and heritageArch's
   * RsvpSection) and they have drifted apart before. More to the point, a
   * client-side rule is a suggestion: this endpoint is public, and a submission
   * that skipped the form entirely would otherwise write a party with no number
   * and `sms_consent = false` — a guest the organizer believes is reachable by
   * text and who can never be texted.
   */
  const isDeclining = response === 'no';
  const hasPhone = phone && String(phone).trim();

  if (!isDeclining && !hasPhone) {
    return sendFail(res, { status: 400, error: 'VALIDATION_ERROR', message: 'A mobile number is required.' });
  }
  // Format-checked whenever one is supplied, including on a decline: a decliner
  // may leave a number for the host's own records, and a malformed one helps
  // nobody. `null` when genuinely absent, which only a decline can now reach.
  const normalizedPhone = hasPhone ? normalizeToE164(phone) : null;
  if (hasPhone && !normalizedPhone) {
    return sendFail(res, { status: 400, error: 'VALIDATION_ERROR', message: 'Enter a valid phone number in international format (e.g. +1 555 123 4567).' });
  }

  /**
   * Consent must be an explicit `true`.
   *
   * `!smsConsent` rather than `smsConsent === false`, so an absent field is a
   * refusal rather than a pass. A client that simply omits the key is exactly
   * the case this check exists for.
   *
   * Everything downstream is unchanged: submit_rsvp_v2 still stamps
   * sms_consent_at on every write, and consent is still re-verified at send
   * time (smsDispatch's gate chain) rather than trusted from this record. A
   * required checkbox is a collection rule; it is not, and must not become, a
   * substitute for the send-time gate.
   */
  if (!isDeclining && !smsConsent) {
    return sendFail(res, {
      status: 400,
      error: 'SMS_CONSENT_REQUIRED',
      message: 'Please agree to receive event texts so we can send your table and entry pass.',
    });
  }

  // Email is required for attendees (confirmation + logistics), optional for a
  // decline; when present it must be valid either way.
  if (isAttending && (!email || !String(email).trim())) {
    return sendFail(res, { status: 400, error: 'VALIDATION_ERROR', message: 'An email address is required.' });
  }
  if (email && String(email).trim() && !EMAIL_RE.test(String(email).trim())) {
    return sendFail(res, { status: 400, error: 'VALIDATION_ERROR', message: 'Enter a valid email address.' });
  }

  if (side !== undefined && side !== null && side !== '' && !['partner1', 'partner2'].includes(side)) {
    return sendFail(res, { status: 400, error: 'VALIDATION_ERROR', message: 'side must be partner1 or partner2.' });
  }

  if (Array.isArray(additionalGuests) && additionalGuests.length > guestService.MAX_ADDITIONAL_GUESTS) {
    return sendFail(res, { status: 400, error: 'VALIDATION_ERROR', message: 'Too many additional guests submitted.' });
  }
  if (Array.isArray(customAnswers) && customAnswers.length > guestService.MAX_CUSTOM_ANSWERS) {
    return sendFail(res, { status: 400, error: 'VALIDATION_ERROR', message: 'Too many custom answers submitted.' });
  }

  // Defense in depth: the frontend only shows an "Update my response" action
  // when the event's allow_guest_edits is on (useRsvpResolver.js) — nothing
  // stops a direct API call otherwise. Reject an edit to an already-answered
  // party server-side too, regardless of whether submit_rsvp_v2 also checks
  // this internally. A first-time response (party.response still 'pending',
  // or no partyId at all) is never blocked by this.
  if (partyId) {
    const { data: existingParty } = await supabase
      .from('rsvp_parties')
      .select('response, events(slug, allow_guest_edits, rsvp_deadline)')
      .eq('id', partyId)
      .maybeSingle();

    const ev = existingParty?.events;
    // Only an EDIT to an already-answered party is gated here — a first-time
    // response (still 'pending', or no partyId) is never blocked by this.
    const editingAnswered = ev?.slug === slug && ['yes', 'no', 'maybe'].includes(existingParty.response);

    if (editingAnswered && !ev?.allow_guest_edits) {
      return sendFail(res, {
        status: 403,
        error: 'RESPONSE_EDITS_DISABLED',
        message: 'The organizer has disabled changes to RSVPs after submission. Please contact them directly to update your response.',
      });
    }
    // Even when edits are allowed, they close at the RSVP deadline — matching the
    // organizer-facing promise ("guests can update their RSVP ... until the RSVP
    // deadline"). Enforced server-side so a direct API call can't slip past it.
    if (editingAnswered && ev?.allow_guest_edits && ev?.rsvp_deadline && new Date() > new Date(ev.rsvp_deadline)) {
      return sendFail(res, {
        status: 403,
        error: 'RESPONSE_EDITS_CLOSED',
        message: 'The deadline to change your RSVP has passed. Please contact the host to make any changes.',
      });
    }
  }

  if (response === 'yes') {
    const size = partySize || 1;
    if (size > 1) {
      if (!Array.isArray(additionalGuests) || additionalGuests.length < size - 1) {
        return sendFail(res, { status: 400, error: 'VALIDATION_ERROR', message: `Please provide details for all ${size - 1} additional guests.` });
      }
      // A companion is a NAME. Contact details, meal and dietary notes belong to
      // the person who opened the invitation and is filling this in; anyone they
      // bring is recorded so the organizer can seat, count and check them in.
      // Requiring an email per companion is what forced households sharing one
      // inbox into idx_guests_event_email_unique, which submit_rsvp_v2 used to
      // "resolve" by silently discarding the address.
      for (let idx = 0; idx < size - 1; idx++) {
        const g = additionalGuests[idx];
        if (!g || !g.fullName || !g.fullName.trim()) {
          return sendFail(res, { status: 400, error: 'VALIDATION_ERROR', message: `Guest #${idx + 2} must have a valid full name.` });
        }
      }
    }
  }

  // Reduced to the one field a companion has. Anything else a caller sends —
  // an old client still posting email/phone/meal, or a hand-rolled request — is
  // dropped here rather than rejected: the submission is valid, the extra keys
  // simply have nowhere to go now, and failing an otherwise-good RSVP over them
  // would be hostile.
  const sanitizedAdditional = Array.isArray(additionalGuests)
    ? additionalGuests
        .filter((g) => g && typeof g.fullName === 'string' && g.fullName.trim())
        .map((g) => ({ fullName: g.fullName.trim() }))
    : [];

  try {
    const result = await guestService.submitPublicRsvp({
      slug, partyId, guestName, email, phone: normalizedPhone, response,
      partySize: partySize || 1, notes, primaryMeal: primaryGuestMeal,
      dietaryNotes: primaryGuestDietaryNotes || null,
      additionalGuests: sanitizedAdditional,
      customAnswers: Array.isArray(customAnswers) ? customAnswers : [],
      declineReason: decline_reason, maybeConfirmBy: maybe_confirm_by,
      side: side || null,
      smsConsent: !!smsConsent,
      // Companion meals arrive as a tally for the group, not a choice per
      // person — see the migration's header. Validated inside the RPC against
      // the event's own meal options.
      companionMealCounts: req.body?.companionMealCounts || null,
    });

    if (!result || result.success === false) {
      return sendRpcFailure(res, result);
    }

    const eventId = result.event_id;
    const computedPartySize = result.party_size;

    // Consent provenance (Privacy Policy §3 record-keeping): stamp which
    // canonical consent-text version the guest was shown and which surface
    // captured the decision. Best-effort second write — never blocks or fails
    // the RSVP; sms_consent + sms_consent_at were already persisted atomically
    // by the RPC.
    //
    // Both the number and the consent are validated above, so `normalizedPhone`
    // is always set and `smsConsent` is always true by the time this runs. The
    // condition is kept as a guard rather than simplified away: this is a
    // best-effort write that must not throw on a party the RPC declined to
    // create, and `result.party_id` is the half of it that can genuinely be
    // absent.
    //
    // The stamp records WHICH wording was agreed to and on which surface — which
    // matters more now, not less: the disclosure changed on 2026-09-04 and
    // consent captured before and after that date is consent to two different
    // notices (see utils/smsConsent.js).
    if (normalizedPhone && result.party_id) {
      const consentSource = normalizeConsentSource(req.body?.consentSource);
      supabase
        .from('rsvp_parties')
        .update({
          sms_consent_text_version: SMS_CONSENT_TEXT_VERSION,
          sms_consent_source: consentSource,
          // The guest has now decided for themselves, so the provenance must say
          // so. submit_rsvp_v2 writes sms_consent/sms_consent_at but has no
          // knowledge of the method columns (they arrived in a later migration),
          // which left a party that was previously host-attested still labelled
          // `host_attested` — with a stale attester and date — even after its
          // guest personally ticked or untucked the box. The dashboard badge read
          // "you confirmed" for a decision the guest made, and the party row
          // contradicted the append-only log written just below.
          sms_consent_method: CONSENT_METHOD_GUEST,
          sms_consent_attested_by: null,
          sms_consent_attested_at: null,
          // The language the guest actually used. Recorded because SCHEDULED
          // messages — reminders sent days later by a job with no request
          // context — otherwise have nothing to read and default to English. A
          // guest who RSVP'd in Arabic and got an Arabic confirmation would then
          // receive their reminder in English.
          preferred_lang: guestLang,
        })
        .eq('id', result.party_id)
        .then(
          ({ error }) => {
            if (error) logger.warn({ err: error, partyId: result.party_id }, 'sms consent provenance write failed (apply 20260809000000_sms_compliance.sql)');
          },
          // A rejected promise here (e.g. a network-layer throw) must never
          // become an unhandled rejection in the hot RSVP path.
          (err) => logger.warn({ err, partyId: result.party_id }, 'sms consent provenance write rejected'),
        );

      // Append-only consent log (Twilio TFV 30475). The columns above are
      // current state on a mutable row; this is the dated, immutable record of
      // the decision itself, with the phone number as it stood at capture time.
      // Logged for a REFUSAL as well as an opt-in — a dated decline is evidence
      // that consent was asked separately and freely declined. Fire-and-forget:
      // consent has already been persisted atomically by the RPC, so this must
      // never block or fail the guest's RSVP.
      logSmsConsentDecision({
        eventId,
        partyId: result.party_id,
        phone: normalizedPhone,
        consent: !!smsConsent,
        source: consentSource,
      });
    }

    broadcast(eventId, 'rsvp_submitted', {
      partyId: result.party_id, guestName, response: result.response, partySize: computedPartySize,
    });

    // Confirmation / decline email (best-effort). A 'maybe' is acknowledged
    // too — it used to fall through both branches and receive nothing at all,
    // which reads to the guest as "my response was never recorded".
    if (result.response === 'yes' || result.response === 'maybe') {
      if (result.guest_email) {
        notificationService.sendConfirmationEmail(eventId, result.party_id, guestLang)
          .catch((err) => logger.error({ err }, 'Confirmation email error'));
      } else {
        logger.warn({ partyId: result.party_id, eventId, response: result.response },
          'RSVP recorded without a guest email — confirmation email skipped');
      }
      // Companions are no longer mailed: they have no address of their own any
      // more. The one confirmation above goes to the person who filled the form
      // in, and it carries the entry pass for the whole party — the QR reads
      // "Admits N" and the door scanner checks in every member on one scan
      // (checkinController.scanCheckIn). notificationService still exports
      // sendCompanionConfirmationEmail; nothing calls it.
    } else if (result.response === 'no' && !result.guest_email) {
      logger.warn({ partyId: result.party_id, eventId }, 'Decline recorded without a guest email — thank-you email skipped');
    } else if (result.response === 'no') {
      // Email only. The decline acknowledgement used to try SMS first and fall
      // back to mail; that type is retired.
      //
      // Of the seven types, this was the one whose text form most reliably read
      // as unwanted — the guest has just said they are not coming, and a CHARGED
      // message telling them "thanks anyway" spends an organizer's allowance to
      // send something nobody asked for. The email costs nothing and says the same
      // thing, so it simply goes.
      const declineHtml = getDeclineConfirmationTemplate(
        { guest_name: guestName },
        { title: result.event_title, event_date: result.event_date, slug: result.event_slug },
        guestLang,
      );
      const declineSubject = guestLang === 'ar'
        ? `شكرًا لإخبارنا – ${escapeHtml(result.event_title)}`
        : `Thank You – ${escapeHtml(result.event_title)}`;
      notificationService.sendEmailViaBrevo(result.guest_email, declineSubject, declineHtml)
        .catch((err) => logger.error({ err }, 'Decline email error'));
    }


    // Notify organizer of the new RSVP (best-effort).
    try {
      const prefs = result.notification_preferences;
      const isEmailPref = !prefs || prefs.email !== false;
      const isWhatsappPref = !!prefs?.whatsapp;
      const respLabel = result.response === 'yes' ? 'Attending' : result.response === 'maybe' ? 'Maybe' : 'Declined';

      // Fetched once and reused by both the organizer and partner emails below
      // so the "Side" row can name the actual groom/bride (template_data.partner1/
      // partner2) instead of the generic "Partner 1/2's Side" fallback.
      let td = {};
      // The event's clock, so the "Submitted" stamp on the organizer's mail
      // reads on their own clock. It rides the template_data query below
      // rather than adding one — the RPC result this handler works from does
      // not carry the column, and a second round-trip on the hot RSVP path to
      // fetch one string would not be worth it.
      let eventTimezone = null;
      // The custom questions, by id, so each answer can be printed under the
      // LABEL the organizer wrote rather than as a bare uuid. One query, and
      // only when this submission actually carried answers.
      let fieldLabels = new Map();
      if (isEmailPref) {
        const answered = Array.isArray(customAnswers)
          ? customAnswers.filter((a) => a && a.fieldId)
          : [];
        const [{ data: eventRow }, fieldRes] = await Promise.all([
          supabase.from('events').select('template_data, timezone').eq('id', eventId).single(),
          answered.length > 0
            ? supabase.from('custom_form_fields').select('id, field_label')
              .eq('event_id', eventId)
              .in('id', answered.map((a) => a.fieldId))
            : Promise.resolve({ data: [] }),
        ]);
        td = eventRow?.template_data || {};
        eventTimezone = eventRow?.timezone || null;
        // Best-effort: a failed label lookup drops the custom rows from the
        // mail, it does not drop the mail.
        fieldLabels = new Map((fieldRes?.data || []).map((f) => [f.id, f.field_label]));
      }

      /**
       * EVERYTHING THE GUEST ACTUALLY TYPED.
       *
       * Read from the request rather than re-queried: this is the submission
       * that was just written, the RPC accepted it verbatim, and a read-back
       * would be a second round-trip on the hot RSVP path to learn what is
       * already in local scope.
       *
       * The one exception is `sms_consent`, which comes off `result` — the RPC
       * is what decides it (a party can arrive already opted in), so the
       * request's checkbox is not authoritative.
       */
      const submissionDetail = {
        phone: normalizedPhone,
        meal: primaryGuestMeal || null,
        dietaryNotes: primaryGuestDietaryNotes || null,
        companions: sanitizedAdditional,
        companionMealCounts: req.body?.companionMealCounts || null,
        customAnswers: (Array.isArray(customAnswers) ? customAnswers : [])
          .map((a) => ({ label: fieldLabels.get(a?.fieldId) || null, value: a?.value }))
          .filter((a) => a.label),
        notes: notes || null,
        declineReason: decline_reason || null,
        maybeConfirmBy: maybe_confirm_by || null,
        smsConsent: result.sms_consent ?? null,
        language: guestLang,
        submittedAt: new Date().toISOString(),
        isUpdate: !!result.is_update,
        timeZone: eventTimezone,
      };

      if (isEmailPref && result.org_email) {
        const orgEmailHtml = getNewRsvpOrganizerTemplate({
          eventTitle: result.event_title, guestName, response: result.response, partySize: computedPartySize, email,
          side: result.side, eventType: result.event_type, partner1Name: td.partner1, partner2Name: td.partner2,
          ...submissionDetail,
        });
        const orgSubject = result.is_update
          ? `RSVP updated: ${escapeHtml(guestName)} - ${escapeHtml(result.event_title)}`
          : `New RSVP: ${escapeHtml(guestName)} - ${escapeHtml(result.event_title)}`;
        notificationService.sendEmailViaBrevo(result.org_email, orgSubject, orgEmailHtml)
          .catch((err) => logger.error({ err }, 'Failed to notify organizer via email'));
      }

      // Also copy in the groom/bride, if the organizer configured their emails
      // on the event (template_data.partner1_email/partner2_email) — same
      // toggle, same template, just a public-page CTA instead of a dashboard one.
      //
      // They get the SAME detail. This is the couple's own family: the whole
      // reason the co-recipient field exists is so they do not have to ask the
      // organizer who is coming and what they eat.
      if (isEmailPref) {
        for (const partnerEmail of [td.partner1_email, td.partner2_email]) {
          if (partnerEmail && EMAIL_RE.test(String(partnerEmail).trim())) {
            const partnerEmailHtml = getNewRsvpOrganizerTemplate({
              eventTitle: result.event_title, guestName, response: result.response, partySize: computedPartySize, email,
              side: result.side, eventType: result.event_type, recipientRole: 'partner', eventSlug: result.event_slug,
              partner1Name: td.partner1, partner2Name: td.partner2,
              ...submissionDetail,
            });
            const partnerSubject = result.is_update
              ? `RSVP updated: ${escapeHtml(guestName)} - ${escapeHtml(result.event_title)}`
              : `New RSVP: ${escapeHtml(guestName)} - ${escapeHtml(result.event_title)}`;
            notificationService.sendEmailViaBrevo(partnerEmail.trim(), partnerSubject, partnerEmailHtml)
              .catch((err) => logger.error({ err }, 'Failed to notify partner recipient via email'));
          }
        }
      }

      if (isWhatsappPref && result.org_phone) {
        const { getTwilioClient, getTwilioWhatsAppFrom } = require('../utils/twilioClient');
        const twilio = getTwilioClient();
        const whatsappFrom = getTwilioWhatsAppFrom();
        const messageText = `New RSVP Received for ${result.event_title}: ${guestName} has replied ${result.response === 'yes' ? 'Attending (Party of ' + computedPartySize + ')' : respLabel}. — Fancy RSVP`;
        if (twilio && whatsappFrom) {
          twilio.messages.create({ body: messageText, from: whatsappFrom, to: `whatsapp:${result.org_phone}` })
            .catch((err) => logger.error({ err }, 'Failed to notify organizer via WhatsApp'));
        } else if (twilio && !whatsappFrom) {
          // Previously this fell back to Twilio's public sandbox number, which only
          // delivers to handsets that manually joined it — so in production the
          // organizer simply never heard about their own RSVPs. Say so instead.
          logger.warn({ eventId }, 'WhatsApp notification skipped — TWILIO_WHATSAPP_FROM is not configured.');
        } else {
          logger.info(`[MOCK WHATSAPP NOTIFICATION] To: ${result.org_phone} | Content: ${messageText}`);
        }
      }
    } catch (orgNotifyErr) {
      logger.error({ err: orgNotifyErr }, 'Organizer notification error');
    }

    // Mint the real entrance QR ticket immediately on a "yes" — see
    // signQrTicketForResponse's doc comment for why this doesn't wait for
    // seating. The success screen (and any later return visit) can now show
    // a genuinely scannable code instead of a decorative placeholder.
    const qrToken = tokenService.signQrTicketForResponse({
      response: result.response, partyId: result.party_id, eventId,
      tableName: null, partySize: computedPartySize, eventDate: result.event_date,
    });

    /**
     * THE CONFIRMATION TEXT, WITH THE GUEST'S OWN DETAILS IN IT.
     *
     * `rsvp_confirmation` was retired here on the grounds that a text saying "we
     * got it" told the guest something they had just done themselves. That was a
     * fair objection to the old message and it does not apply to this one: it
     * carries the date, the venue, who is coming with them, what was ordered for
     * each of them, and their pass link — the questions an organizer otherwise
     * answers by hand, one guest at a time.
     *
     * ── Deliberately fire-and-forget ──
     *
     * The RSVP is already committed. Awaiting a carrier round trip here would make
     * a guest watch a spinner for something that is not about them, and a carrier
     * outage would turn a successful RSVP into an error on their screen. Every
     * gate (entitlement, the organizer's switch, consent, STOP, balance) lives
     * inside sendTransactionalSms; nothing needs re-checking here.
     *
     * ── No table yet, on purpose ──
     *
     * At submission time nobody has seated them, so `tableName` is absent and the
     * template omits that clause rather than inventing one. `seating_reminder`
     * covers the table later — when it is actually known.
     */
    if (result.response === 'yes') {
      (async () => {
        const [{ data: ev }, { data: party }] = await Promise.all([
          supabase.from('events')
            .select('id, title, slug, event_date, timezone, location_name, location_address, sms_addon_purchased_at, sms_settings, sms_templates')
            .eq('id', eventId).single(),
          // Read the COMMITTED party rather than rebuilding it from the request
          // body: the RPC has already normalized names, party size and meals, and
          // this is the same shape the guest's own ticket page renders from — so
          // the text and the page it links to cannot disagree.
          supabase.from('rsvp_parties')
            .select('id, label, preferred_lang, companion_meal_counts, guests(full_name, is_primary_contact, meal_selection)')
            .eq('id', result.party_id).single(),
        ]);
        if (!ev?.sms_addon_purchased_at || !party) return;

        const members = party.guests || [];
        const companions = members
          .filter((g) => !g.is_primary_contact && g.full_name)
          .map((g) => g.full_name);

        // One tally for the whole party — "Beef Steak x2, Fish x1" says what was
        // ordered in far fewer characters than naming a dish per person, and
        // characters are segments.
        const tally = {};
        for (const g of members) {
          if (g.meal_selection) tally[g.meal_selection] = (tally[g.meal_selection] || 0) + 1;
        }
        for (const [meal, n] of Object.entries(party.companion_meal_counts || {})) {
          if (meal && Number(n) > 0) tally[meal] = (tally[meal] || 0) + Number(n);
        }
        const meals = Object.entries(tally)
          .sort((a, b) => b[1] - a[1])
          .map(([meal, n]) => (n > 1 ? `${meal} x${n}` : meal));

        const { sendTransactionalSms } = require('../services/smsDispatch');
        const T = require('../utils/emailTemplates');

        await sendTransactionalSms({
          type: 'rsvp_confirmation',
          eventId,
          partyId: party.id,
          // Keyed on the party alone: one confirmation per guest, ever. A guest who
          // edits their RSVP twice must not be charged for three copies of the
          // same message, and the (kind, ref) unique index is what guarantees it.
          ref: `rsvpconf:${party.id}`,
          event: ev,
          lang: party.preferred_lang || 'en',
          context: {
            guestName: party.label || guestName,
            eventTitle: ev.title,
            dateLabel: T.formatEventDate ? T.formatEventDate(ev.event_date, ev.timezone) : null,
            venue: ev.location_name || ev.location_address || null,
            tableName: null,
            companions,
            meals,
            ticketUrl: qrToken ? T.buildTicketLinks(qrToken).ticketUrl : null,
          },
        });
      })().catch((err) => logger.warn({ err, eventId }, 'RSVP confirmation text failed'));
    }

    return sendOk(res, {
      partyId: result.party_id,
      message: result.is_update ? 'RSVP updated successfully.' : 'RSVP submitted successfully.',
      qrToken,
    }, { status: 201 });
  } catch (err) {
    if (isGuestLimitError(err)) {
      return sendFail(res, { status: 409, error: 'GUEST_LIMIT_REACHED', message: 'This event has reached its plan\'s guest limit. Contact the organizer.' });
    }
    next(err);
  }
};

/**
 * Resolves a single party invitation by its party id (public endpoint).
 * GET /api/v1/public/rsvp/guest/:guestId
 */
const getGuestById = async (req, res, next) => {
  const { guestId: partyId } = req.params;
  try {
    const resolved = await guestService.getPartyForPublicResolve(partyId);
    if (!resolved) return sendFail(res, { status: 404, error: 'GUEST_NOT_FOUND' });
    if (!isEventLiveForGuests(resolved.event)) return sendFail(res, { status: 404, error: 'EVENT_INACTIVE' });

    const qrToken = tokenService.signQrTicketForResponse({
      response: resolved.response, partyId: resolved.id, eventId: resolved.eventId,
      tableName: resolved.tableName, partySize: resolved.partySize, eventDate: resolved.event.event_date,
    });

    return sendOk(res, {
      slug: resolved.event.slug,
      seatingLocked: !resolved.seatingRevealed,
      revealAt: resolved.revealAt,
      guest: {
        id: resolved.id,
        guest_name: resolved.label,
        party_size: resolved.partySize,
        response: resolved.response,
        table_name: resolved.tableName,
        qrToken,
      },
    });
  } catch (err) {
    next(err);
  }
};

