#!/usr/bin/env node
/**
 * ═══════════════════════════════════════════════════════════════════════════
 * GENERATE THE MIGRATION-LEDGER BASELINE
 *
 * ── THE PROBLEM THIS EXISTS FOR ──
 *
 * On 2026-09-10 a read of the live database returned:
 *
 *     supabase_migrations.schema_migrations : EXISTS
 *     rows recorded                         : 0
 *
 * Zero. Not "my two are missing" — the ledger is EMPTY, while the schema itself
 * carries all 122 migrations' worth of tables, functions, triggers and indexes.
 * This project has never run `supabase db push`; every migration has been pasted
 * into the SQL editor by hand, which applies the SQL and records nothing.
 *
 * A database whose schema is current and whose ledger is empty is a loaded gun.
 * The first person to run `supabase db push`, `supabase db reset`, or to restore
 * a backup through the CLI gets the whole chain replayed from file #1 against a
 * database that already has everything. Much of that chain is idempotent. Much
 * of it is not:
 *
 *     20260703000000  DROP MATERIALIZED VIEW mv_daily_revenue
 *     20260705000000  ALTER TABLE rsvp_form_fields RENAME TO custom_form_fields
 *     20260727000000  backfill UPDATEs over live rows
 *     …plus every CREATE POLICY with no DROP POLICY before it
 *
 * It would fail partway. The question is only what it had already done by then.
 *
 * ── WHAT THIS PRODUCES ──
 *
 * A SQL file that INSERTs one row per migration file into the ledger WITHOUT
 * running any of them, so the CLI's view of the world matches reality and
 * `db push` applies only what is genuinely new.
 *
 *     node backend/scripts/generate-migration-baseline.js
 *     node backend/scripts/generate-migration-baseline.js --through 20260910010000
 *
 * `--through` is the important flag: everything at or before that version is
 * marked applied, everything after is left for `db push` to run normally.
 * Defaults to the newest migration that is NOT the one still pending.
 *
 * ── THE RISK, STATED PLAINLY ──
 *
 * This asserts that the listed migrations HAVE been applied. If one of them
 * never actually ran, baselining means it never will — the CLI will skip it
 * forever, and the missing column or trigger surfaces later as a PostgREST 400
 * naming a column rather than a missing migration.
 *
 * The evidence that the chain really is applied is good but not total: the
 * 2026-09-10 audit confirmed the tables, the RLS state, the eight newest indexes
 * and six named functions all exist. It did not check all 122 files.
 *
 * So: run `node backend/scripts/audit-schema.js` and, if the CLI is linked,
 * `supabase db diff` AFTER baselining. A clean diff is the proof. A dirty one
 * names exactly what to apply by hand.
 * ═══════════════════════════════════════════════════════════════════════════
 */

const fs = require('fs');
const path = require('path');

const MIGRATIONS_DIR = path.join(__dirname, '..', '..', 'supabase', 'migrations');
const OUT_FILE = path.join(__dirname, '..', '..', 'supabase', 'BASELINE-schema-migrations.sql');

/** `20260911000000_foo.sql` → { version: '20260911000000', name: 'foo' } */
function parse(fileName) {
  const base = fileName.replace(/\.sql$/i, '');
  const underscore = base.indexOf('_');
  if (underscore === -1) return { version: base, name: base };
  return { version: base.slice(0, underscore), name: base.slice(underscore + 1) };
}

function main() {
  const argv = process.argv.slice(2);
  const throughIdx = argv.indexOf('--through');
  const explicitThrough = throughIdx !== -1 ? argv[throughIdx + 1] : null;

  const files = fs.readdirSync(MIGRATIONS_DIR)
    .filter((f) => f.toLowerCase().endsWith('.sql'))
    .sort();

  if (files.length === 0) {
    console.error('No migrations found in', MIGRATIONS_DIR);
    process.exit(1);
  }

  const all = files.map(parse);

  // Default: everything except the newest file, which is assumed to be the one
  // still waiting to be applied. Explicit --through beats the guess.
  const through = explicitThrough || all[all.length - 2]?.version || all[all.length - 1].version;

  const applied = all.filter((m) => m.version <= through);
  const pending = all.filter((m) => m.version > through);

  const lines = [];
  lines.push('-- ═══════════════════════════════════════════════════════════════════════');
  lines.push('-- MIGRATION LEDGER BASELINE');
  lines.push(`-- Generated by backend/scripts/generate-migration-baseline.js on ${new Date().toISOString()}`);
  lines.push('--');
  lines.push('-- This RECORDS migrations as applied. It does NOT run them. Paste it into the');
  lines.push('-- Supabase SQL editor once, on a database whose schema is already current.');
  lines.push('--');
  lines.push(`-- Marks applied : ${applied.length} migrations, through ${through}`);
  lines.push(`-- Leaves pending: ${pending.length} (${pending.map((m) => m.version).join(', ') || 'none'})`);
  lines.push('--');
  lines.push('-- AFTERWARDS, PROVE IT: run `supabase db diff` (or');
  lines.push('-- `node backend/scripts/audit-schema.js`). A clean result means the baseline was');
  lines.push('-- honest. A dirty one names exactly what was never applied — apply that by hand,');
  lines.push('-- because the CLI will now skip it forever.');
  lines.push('-- ═══════════════════════════════════════════════════════════════════════');
  lines.push('');
  lines.push('BEGIN;');
  lines.push('');
  lines.push('-- The ledger lives in its own schema and may not exist on a database that has');
  lines.push('-- never been touched by the CLI. Creating it here is what makes this safe to run');
  lines.push('-- before the first `db push` rather than after it.');
  lines.push('CREATE SCHEMA IF NOT EXISTS supabase_migrations;');
  lines.push('');
  lines.push('CREATE TABLE IF NOT EXISTS supabase_migrations.schema_migrations (');
  lines.push('  version    TEXT PRIMARY KEY,');
  lines.push('  statements TEXT[],');
  lines.push('  name       TEXT');
  lines.push(');');
  lines.push('');
  lines.push('-- `statements` is left NULL on purpose: it is the CLI\'s record of what it ran,');
  lines.push('-- and it ran nothing. Filling it with the file contents would claim otherwise.');
  lines.push('--');
  lines.push('-- ON CONFLICT DO NOTHING so this is re-runnable and so it can never overwrite a');
  lines.push('-- row the CLI wrote itself.');
  lines.push('INSERT INTO supabase_migrations.schema_migrations (version, name) VALUES');

  const values = applied.map((m, i) => {
    const comma = i === applied.length - 1 ? '' : ',';
    return `  ('${m.version}', ${sqlLiteral(m.name)})${comma}`;
  });
  lines.push(...values);
  lines.push('ON CONFLICT (version) DO NOTHING;');
  lines.push('');
  lines.push('-- What the ledger looks like afterwards.');
  lines.push('SELECT count(*) AS recorded, min(version) AS oldest, max(version) AS newest');
  lines.push('FROM supabase_migrations.schema_migrations;');
  lines.push('');
  lines.push('COMMIT;');
  lines.push('');

  fs.writeFileSync(OUT_FILE, lines.join('\n'), 'utf8');

  console.log(`Wrote ${path.relative(path.join(__dirname, '..', '..'), OUT_FILE)}`);
  console.log(`  marks applied : ${applied.length} (through ${through})`);
  console.log(`  leaves pending: ${pending.length}${pending.length ? ` → ${pending.map((m) => m.version).join(', ')}` : ''}`);
}

/** Single-quote a SQL string literal, doubling any embedded quote. */
function sqlLiteral(s) {
  return `'${String(s).replace(/'/g, "''")}'`;
}

if (require.main === module) main();

module.exports = { parse };
